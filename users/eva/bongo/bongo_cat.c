// Adapted from the central 48x32 artwork to fit a 32x24 portrait header.
// Select the frame from synchronized keypress state, rather than local WPM.
void render_bongo_cat(uint8_t frame) {
    const char *image = waiting_frame;
    if (frame == 1 || frame == 2) image = animation_frames[frame - 1];
    else if (frame == 3) image = ready_frame;
    oled_set_cursor(0, 0);
    oled_write_raw_P(image, ANIM_SIZE);
}
