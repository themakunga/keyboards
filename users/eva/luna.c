void render_luna(const eva_pet_state_t *pet) {
    static uint32_t last_frame;
    static uint8_t frame, last_jump;
    static bool initialized;
    if (!pet->awake) {
        oled_off();
        return;
    }
    oled_on();
    if (initialized && timer_elapsed32(last_frame) < 200) return;
    initialized = true;
    last_frame = timer_read32();
    frame ^= 1;
    const char *image = pet->caps ? bark[frame] :
                        pet->mods & MOD_MASK_CTRL ? sneak[frame] :
                        pet->wpm <= 10 ? sit[frame] :
                        pet->wpm <= 40 ? walk[frame] : run[frame];
    // Keep short Space taps visible even when press/release precede the next RPC or frame.
    bool jumping = pet->space || pet->jumps != last_jump;
    last_jump = pet->jumps;
#ifdef EVA_OLED_SPLIT_STATUS
    const uint8_t row = 3;
#else
    const uint8_t row = 4;
#endif
    // Write final bytes directly so erasing a frame cannot starve the history below it.
    for (uint8_t page = 0; page < 4; ++page) {
        uint8_t sprite_page = jumping ? page : page - 1;
        for (uint8_t x = 0; x < 32; ++x) {
            uint8_t data = sprite_page < 3 ? pgm_read_byte(&image[sprite_page * 32 + x]) : 0;
            oled_write_raw_byte(data, (row - 1 + page) * 32 + x);
        }
    }
}
